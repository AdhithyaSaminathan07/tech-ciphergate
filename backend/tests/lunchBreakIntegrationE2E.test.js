// backend/tests/lunchBreakIntegrationE2E.test.js
const assert = require('assert');
const jwt = require('jsonwebtoken');
const { calculateWorkerProductivity } = require('../utils/productivityCalculator');

console.log('================================================================');
console.log(' Tech Ciphergate — Lunch Break E2E Integration Verification Suite');
console.log('================================================================\n');

let passed = 0;
let failed = 0;

function runStep(stepNumber, stepName, fn) {
  try {
    fn();
    console.log(`✓ [STEP ${stepNumber} PASS] ${stepName}`);
    passed++;
  } catch (error) {
    console.error(`✗ [STEP ${stepNumber} FAIL] ${stepName}`);
    console.error(`  Error: ${error.message}\n${error.stack}`);
    failed++;
  }
}

async function runAsyncStep(stepNumber, stepName, fn) {
  try {
    await fn();
    console.log(`✓ [STEP ${stepNumber} PASS] ${stepName}`);
    passed++;
  } catch (error) {
    console.error(`✗ [STEP ${stepNumber} FAIL] ${stepName}`);
    console.error(`  Error: ${error.message}\n${error.stack}`);
    failed++;
  }
}

async function runCompleteIntegrationWorkflow() {
  const JWT_SECRET = 'e2e-audit-secret-key-98765';
  process.env.JWT_SECRET = JWT_SECRET;

  // In-Memory Database Store for Isolation
  const db = {
    settings: {},
    workers: {},
    refreshTokens: [],
    attendances: []
  };

  const subdomain = 'tech-cipher-e2e';
  const targetDate = '2026-11-06';

  // Seed initial worker and tenant data
  const workerId = 'worker_e2e_001';
  db.workers[workerId] = {
    _id: workerId,
    name: 'Kavitha S',
    username: 'kavitha',
    rfid: 'RFID_KAVITHA_99',
    subdomain,
    department: 'dept_eng',
    departmentName: 'Engineering',
    status: 'Active',
    salary: 54000,
    batch: 'Standard Shift',
    sessionInvalidatedAt: null,
    lastLunchOutDate: null
  };

  // Morning punch-in by employee at 09:00:00 AM IST
  const morningDateObj = new Date('2026-11-06T09:00:00+05:30');
  db.attendances.push({
    _id: 'att_001',
    worker: workerId,
    name: 'Kavitha S',
    username: 'kavitha',
    rfid: 'RFID_KAVITHA_99',
    subdomain,
    date: targetDate,
    time: '09:00:00 AM',
    presence: true,
    punchType: 'REGULAR',
    source: 'MANUAL',
    isLunchPunch: false,
    createdAt: morningDateObj,
    record: { presence: true, isAutoGenerated: false }
  });

  // Morning login: Worker was issued access and refresh tokens at 09:00:00 AM IST
  const morningIat = Math.floor(morningDateObj.getTime() / 1000);
  const morningAccessToken = jwt.sign(
    { id: workerId, role: 'worker', iat: morningIat },
    JWT_SECRET
  );
  db.refreshTokens.push({ userId: workerId, token: 'refresh_token_morning_123' });

  // ─────────────────────────────────────────────────────────────────
  // STEP 1: Admin configures lunch timings
  // ─────────────────────────────────────────────────────────────────
  runStep(1, 'Admin configures lunch timings in Settings', () => {
    db.settings[subdomain] = {
      subdomain,
      lunchBreakManagement: {
        enabled: true,
        lunchOutTime: '13:30',
        returnDeadline: '14:30',
        gracePeriodMinutes: 5,
        appliesTo: 'all'
      }
    };

    const config = db.settings[subdomain].lunchBreakManagement;
    assert.strictEqual(config.enabled, true, 'Lunch management must be enabled');
    assert.strictEqual(config.lunchOutTime, '13:30', 'Lunch out time must match 13:30');
    assert.strictEqual(config.returnDeadline, '14:30', 'Return deadline must match 14:30');
    assert.strictEqual(config.gracePeriodMinutes, 5, 'Grace period must be 5 minutes');
  });

  // ─────────────────────────────────────────────────────────────────
  // STEP 2: Backend scheduler detects the configured lunch-out time
  // ─────────────────────────────────────────────────────────────────
  let detectedLunchOut = false;
  runStep(2, 'Backend scheduler detects configured lunch-out time (13:30 IST)', () => {
    const config = db.settings[subdomain].lunchBreakManagement;
    const simulatedISTTime24 = '13:30';

    const timeToMinutes = (timeStr) => {
      const [h, m] = timeStr.split(':').map(Number);
      return h * 60 + m;
    };

    const currentMinutes = timeToMinutes(simulatedISTTime24);
    const lunchOutMinutes = timeToMinutes(config.lunchOutTime);
    const returnDeadlineMinutes = timeToMinutes(config.returnDeadline);
    const cutoffMinutes = returnDeadlineMinutes + config.gracePeriodMinutes;

    if (currentMinutes >= lunchOutMinutes && currentMinutes <= cutoffMinutes) {
      detectedLunchOut = true;
    }

    assert.strictEqual(detectedLunchOut, true, 'Scheduler must detect current time is within lunch window');
  });

  // ─────────────────────────────────────────────────────────────────
  // STEP 3: Employee attendance receives automatic LUNCH_OUT
  // ─────────────────────────────────────────────────────────────────
  const lunchOutTimeStr = '01:30:00 PM';
  const lunchOutDateObj = new Date('2026-11-06T13:30:00+05:30');

  await runAsyncStep(3, 'Employee attendance receives automatic LUNCH_OUT event', async () => {
    const worker = db.workers[workerId];

    // Atomic concurrency lock on Worker
    if (worker.lastLunchOutDate === targetDate) {
      throw new Error('Worker already locked for lunch today');
    }
    worker.lastLunchOutDate = targetDate;
    worker.sessionInvalidatedAt = lunchOutDateObj;

    // Create automatic LUNCH_OUT attendance event
    const lunchOutRecord = {
      _id: 'att_002',
      worker: workerId,
      name: worker.name,
      username: worker.username,
      rfid: worker.rfid,
      subdomain: worker.subdomain,
      date: targetDate,
      time: lunchOutTimeStr,
      presence: false,
      punchType: 'LUNCH_OUT',
      source: 'SYSTEM/AUTOMATIC',
      isLunchPunch: true,
      isMissingLunchReturn: false,
      createdAt: lunchOutDateObj,
      record: { presence: false, isAutoGenerated: false, punchType: 'LUNCH_OUT', isLunchPunch: true }
    };
    db.attendances.push(lunchOutRecord);

    // Delete refresh tokens
    db.refreshTokens = db.refreshTokens.filter(rt => rt.userId !== workerId);

    assert.strictEqual(lunchOutRecord.presence, false, 'Presence must be false');
    assert.strictEqual(lunchOutRecord.punchType, 'LUNCH_OUT', 'punchType must be LUNCH_OUT');
    assert.strictEqual(lunchOutRecord.source, 'SYSTEM/AUTOMATIC', 'Source must be SYSTEM/AUTOMATIC');
    assert.strictEqual(db.refreshTokens.length, 0, 'Worker refresh tokens must be cleared');
  });

  // ─────────────────────────────────────────────────────────────────
  // STEP 4: Employee session is invalidated
  // ─────────────────────────────────────────────────────────────────
  runStep(4, 'Employee session is invalidated (access token rejected at API middleware)', () => {
    const worker = db.workers[workerId];
    const decodedMorningToken = jwt.verify(morningAccessToken, JWT_SECRET);

    // Simulating authMiddleware token verification logic
    let tokenValid = true;
    let authError = null;

    if (worker.sessionInvalidatedAt) {
      const invalidatedTimestamp = parseInt(new Date(worker.sessionInvalidatedAt).getTime() / 1000, 10);
      if (decodedMorningToken.iat < invalidatedTimestamp) {
        tokenValid = false;
        authError = 'Session invalidated. Please log in again.';
      }
    }

    assert.strictEqual(tokenValid, false, 'Pre-lunch access token must be invalidated');
    assert.strictEqual(authError, 'Session invalidated. Please log in again.', 'Error message must match');
  });

  // ─────────────────────────────────────────────────────────────────
  // STEP 5: Employee logs in again
  // ─────────────────────────────────────────────────────────────────
  let afternoonAccessToken = null;
  runStep(5, 'Employee logs in again and receives fresh JWT', () => {
    const worker = db.workers[workerId];
    // Login at 14:40 IST (after lunch out)
    const loginTimestamp = Math.floor(new Date('2026-11-06T14:40:00+05:30').getTime() / 1000);
    afternoonAccessToken = jwt.sign(
      { id: worker._id, role: 'worker', iat: loginTimestamp },
      JWT_SECRET
    );
    db.refreshTokens.push({ userId: worker._id, token: 'refresh_token_afternoon_456' });

    const decodedAfternoonToken = jwt.verify(afternoonAccessToken, JWT_SECRET);
    const invalidatedTimestamp = parseInt(new Date(worker.sessionInvalidatedAt).getTime() / 1000, 10);

    // New token was issued after invalidation
    assert(decodedAfternoonToken.iat >= invalidatedTimestamp, 'New token timestamp must be >= sessionInvalidatedAt');
    assert.strictEqual(db.refreshTokens.length, 1, 'Worker must have valid active refresh token');
  });

  // ─────────────────────────────────────────────────────────────────
  // STEP 6: Employee punches in after lunch
  // ─────────────────────────────────────────────────────────────────
  let returnPunchRecord = null;
  await runAsyncStep(6, 'Employee punches in after lunch (LUNCH_IN created)', async () => {
    const worker = db.workers[workerId];
    const newPresence = true;
    const current24 = '14:45';
    const currentTimeFormatted = '02:45:00 PM';
    const returnDateObj = new Date('2026-11-06T14:45:00+05:30');

    // Simulated resolveLunchReturnDetails in attendanceController.js
    const lastPunchToday = db.attendances
      .filter(a => a.worker === workerId && a.date === targetDate)
      .sort((a, b) => b.createdAt.getTime() - a.createdAt.getTime())[0];

    assert(lastPunchToday && lastPunchToday.punchType === 'LUNCH_OUT', 'Last punch must be LUNCH_OUT');

    let punchType = 'REGULAR';
    let isLunchPunch = false;
    let lunchLateMinutes = 0;

    if (newPresence === true && lastPunchToday && lastPunchToday.punchType === 'LUNCH_OUT' && !lastPunchToday.presence) {
      punchType = 'LUNCH_IN';
      isLunchPunch = true;

      const lunchConfig = db.settings[subdomain].lunchBreakManagement;
      if (lunchConfig && lunchConfig.enabled) {
        const [currH, currM] = current24.split(':').map(Number);
        const currentMinutes = currH * 60 + currM;

        const [deadH, deadM] = (lunchConfig.returnDeadline || '14:30').split(':').map(Number);
        const deadlineMinutes = deadH * 60 + deadM;
        const grace = lunchConfig.gracePeriodMinutes || 0;
        const threshold = deadlineMinutes + grace;

        if (currentMinutes > threshold) {
          lunchLateMinutes = currentMinutes - threshold;
        }
      }
    }

    returnPunchRecord = {
      _id: 'att_003',
      worker: workerId,
      name: worker.name,
      username: worker.username,
      rfid: worker.rfid,
      subdomain: worker.subdomain,
      date: targetDate,
      time: currentTimeFormatted,
      presence: true,
      punchType,
      source: 'MANUAL',
      isLunchPunch,
      lunchLateMinutes,
      createdAt: returnDateObj,
      record: { presence: true, isAutoGenerated: false, punchType, isLunchPunch, lunchLateMinutes }
    };
    db.attendances.push(returnPunchRecord);

    assert.strictEqual(returnPunchRecord.punchType, 'LUNCH_IN', 'Punch type must be LUNCH_IN');
    assert.strictEqual(returnPunchRecord.isLunchPunch, true, 'isLunchPunch must be true');
    assert.strictEqual(returnPunchRecord.presence, true, 'Presence must be true');
  });

  // ─────────────────────────────────────────────────────────────────
  // STEP 7: Correct lunch return time and late minutes are recorded
  // ─────────────────────────────────────────────────────────────────
  runStep(7, 'Correct lunch return time and late minutes are recorded', () => {
    assert.strictEqual(returnPunchRecord.time, '02:45:00 PM', 'Return punch time must match 02:45:00 PM');
    // Deadline: 14:30 + 5m grace = 14:35 threshold. Punch: 14:45. Late minutes = 10.
    assert.strictEqual(returnPunchRecord.lunchLateMinutes, 10, 'Expected exact 10 late minutes after 5m grace');
  });

  // Shift end punch-out at 19:00:00 PM
  db.attendances.push({
    _id: 'att_004',
    worker: workerId,
    name: 'Kavitha S',
    username: 'kavitha',
    rfid: 'RFID_KAVITHA_99',
    subdomain,
    date: targetDate,
    time: '07:00:00 PM',
    presence: false,
    punchType: 'REGULAR',
    source: 'MANUAL',
    createdAt: new Date('2026-11-06T19:00:00+05:30'),
    record: { presence: false, isAutoGenerated: false }
  });

  // ─────────────────────────────────────────────────────────────────
  // STEP 8: Existing Ciphergate salary engine calculates deduction
  // ─────────────────────────────────────────────────────────────────
  runStep(8, 'Existing Ciphergate salary engine calculates exact late deduction', () => {
    const worker = db.workers[workerId];
    const dayPunches = db.attendances.filter(a => a.worker === workerId && a.date === targetDate);

    const report = calculateWorkerProductivity({
      worker,
      attendanceData: dayPunches,
      fromDate: '2026-11-01',
      toDate: '2026-11-30',
      options: {
        batches: [{
          batchName: 'Standard Shift',
          from: '09:00',
          to: '19:00',
          lunchFrom: '13:30',
          lunchTo: '14:30'
        }],
        lunchBreakManagement: db.settings[subdomain].lunchBreakManagement
      }
    });

    assert.ok(report, 'Salary report must be produced');

    // Total permission/delay minutes must be EXACTLY 10 minutes
    assert.strictEqual(report.totalPermissionTime, 10, `Expected 10 total delay minutes, got ${report.totalPermissionTime}`);

    // Standard working day rate check:
    // Monthly salary: 54000. Working days: 25. Per day salary: 2160.
    // Standard working minutes: 540 (09:00 - 19:00 minus 60 min lunch).
    // Per-minute salary: 2160 / 540 = 4.0.
    // Expected deduction for 10 late minutes: 10 * 4.0 = ₹40.00.
    assert.strictEqual(report.summary.permissionDeduction, 40, `Expected ₹40.00 permission deduction, got ₹${report.summary.permissionDeduction}`);
    assert.strictEqual(report.summary.actualWorkingDays, 1, 'Actual working days must be 1');
  });

  // ─────────────────────────────────────────────────────────────────
  // STEP 9: Admin overview displays correct attendance status
  // ─────────────────────────────────────────────────────────────────
  runStep(9, 'Admin overview displays correct attendance and deduction status', () => {
    const worker = db.workers[workerId];
    const lunchConfig = db.settings[subdomain].lunchBreakManagement;
    const dayPunches = db.attendances.filter(a => a.worker === workerId && a.date === targetDate);

    // Simulated getLunchAttendanceOverview logic
    const lunchOutPunch = dayPunches.find(p => p.punchType === 'LUNCH_OUT' || (p.isLunchPunch && !p.presence));
    const lunchInPunch = dayPunches.find(p => p.punchType === 'LUNCH_IN' || (p.isLunchPunch && p.presence));

    let status = 'Regular Work';
    let lunchOutTime = '-';
    let returnTime = '-';
    let lateMinutes = 0;
    let deductionStatus = 'No Deduction';

    if (lunchOutPunch) {
      lunchOutTime = lunchOutPunch.time;

      if (lunchInPunch) {
        returnTime = lunchInPunch.time;
        lateMinutes = lunchInPunch.lunchLateMinutes || 0;
        if (lateMinutes > 0) {
          status = 'Late Return';
          deductionStatus = `${lateMinutes} mins late-coming deduction`;
        } else {
          status = 'Returned On-Time';
          deductionStatus = 'Within Allowed Limit';
        }
      }
    }

    const overviewItem = {
      workerId: worker._id,
      name: worker.name,
      department: worker.departmentName,
      lunchOutTime,
      lunchOutSource: lunchOutPunch.source,
      expectedReturnTime: lunchConfig.returnDeadline,
      gracePeriodMinutes: lunchConfig.gracePeriodMinutes,
      actualReturnTime: returnTime,
      lateMinutes,
      status,
      deductionStatus,
      isMissingLunchReturn: false
    };

    assert.strictEqual(overviewItem.lunchOutTime, '01:30:00 PM', 'Lunch out time must match');
    assert.strictEqual(overviewItem.lunchOutSource, 'SYSTEM/AUTOMATIC', 'Source must match SYSTEM/AUTOMATIC');
    assert.strictEqual(overviewItem.expectedReturnTime, '14:30', 'Return deadline must match 14:30');
    assert.strictEqual(overviewItem.gracePeriodMinutes, 5, 'Grace period must be 5');
    assert.strictEqual(overviewItem.actualReturnTime, '02:45:00 PM', 'Actual return time must match');
    assert.strictEqual(overviewItem.lateMinutes, 10, 'Late minutes must match 10');
    assert.strictEqual(overviewItem.status, 'Late Return', 'Status must be Late Return');
    assert.strictEqual(overviewItem.deductionStatus, '10 mins late-coming deduction', 'Deduction status must match');
    assert.strictEqual(overviewItem.isMissingLunchReturn, false, 'Missing lunch return must be false');
  });

  console.log('\n================================================================');
  console.log(` E2E Integration Summary: ${passed} Steps Passed, ${failed} Failed out of ${passed + failed} Total Steps`);
  console.log('================================================================');

  if (failed > 0) {
    process.exit(1);
  }
}

runCompleteIntegrationWorkflow();
