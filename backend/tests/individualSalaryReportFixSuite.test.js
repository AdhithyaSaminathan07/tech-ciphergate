// Helper to generate attendance records
function generateAttendance(dateStr, punchIn = '09:00 AM', punchOut = '06:00 PM') {
  return [
    {
      date: dateStr,
      time: punchIn,
      presence: true,
      originalTime: punchIn,
      isAutoGenerated: false
    },
    {
      date: dateStr,
      time: punchOut,
      presence: false,
      originalTime: punchOut,
      isAutoGenerated: false
    }
  ];
}

