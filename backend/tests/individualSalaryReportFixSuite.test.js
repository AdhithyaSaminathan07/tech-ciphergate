// Test 12: Unauthorized absence 5X without duplicate LOP (Option B)
console.log('\nTest 12: Unauthorized absence 5X without duplicate LOP (Option B)...');
{
  const worker = {
    _id: 'w12',
    salary: 27000,
    status: 'Active',
    batch: 'Full Time',
    joiningDate: '2025-01-01',
    relievedAt: null
  };
  // 26 days worked, 1 unauthorized absence on 2026-10-01
  const attendance = [];
  for (let d = 2; d <= 31; d++) {
    const dayDate = new Date(2026, 9, d);
    if (dayDate.getDay() !== 0) {
      attendance.push(...generateAttendance(`2026-10-${String(d).padStart(2, '0')}`));
    }
  }

  const { totalUnauthorizedPenalty, unauthorizedDates } = calculateUnauthorizedAbsencePenalty(
    worker,
    '2026-10-01',
    '2026-10-31',
    [],
    attendance,
    [],
    { advancedLeaveDeduction: { enableUnauthorizedLeavePenalty: true } }
  );
  assert.strictEqual(totalUnauthorizedPenalty, 5000);
  assert.strictEqual(unauthorizedDates.has('2026-10-01'), true);

  const report = calculateWorkerProductivity({
    worker,
    attendanceData: attendance,
    fromDate: '2026-10-01',
    toDate: '2026-10-31',
    options: {
      batches: [{ batchName: 'Full Time', from: '09:00', to: '18:00', isLunchConsider: true }],
      advancedLeaveDeduction: { enableUnauthorizedLeavePenalty: true },
      unauthorizedAbsenceDates: unauthorizedDates
    }
  });

  // Under Option B, normal absent deduction for the unauthorized day is 0 (replaced by 5X)
  assert.strictEqual(report.summary.absentDeduction, 0);

  const finalSalaryAfterPenalty = Math.max(0, report.summary.finalSalary - totalUnauthorizedPenalty);
  const finalized = finalizeSalaryCalculation({
    finalSalaryWithAdjustment: finalSalaryAfterPenalty,
    totalUnauthorizedPenalty
  });
  // 27000 - 5000 = 22000
  assert.strictEqual(finalized.finalPayableSalary, 22000);
  console.log('✓ PASS: Option B verified: LOP is 0 on unauthorized date; exactly 5X deducted.');
}

