// Test 5: Attendance before and after relieving date (Requirement 4 & 5)
console.log('\nTest 5: Attendance before and after relieving date...');
{
  const worker = {
    _id: 'w5',
    salary: 15000,
    status: 'Active',
    joiningDate: '2025-01-01',
    relievedAt: '2026-10-15'
  };
  const dates = getValidatedEmploymentDates(worker, '2026-10-01', '2026-10-31');
  assert.strictEqual(dates.relievedDateStr, '2026-10-15');

  // Employee punched in on Oct 10 (employed) and on Oct 20 (after relieving date)
  const attendance = [
    ...generateAttendance('2026-10-10'),
    ...generateAttendance('2026-10-20')
  ];

  const report = calculateWorkerProductivity({
    worker,
    attendanceData: attendance,
    fromDate: '2026-10-01',
    toDate: '2026-10-31',
    options: {}
  });

  // Working days up to Oct 15 in Oct 2026: Oct 1-15 minus Sundays (Oct 4, 11) = 13 working days
  assert.strictEqual(report.summary.saasWorkingDaysCount, 13);
  const expectedBase = (13 * (15000 / 27));
  assert.strictEqual(report.summary.expectedSaaSSalary.toFixed(2), expectedBase.toFixed(2));

  // Check Oct 20 row in dailyBreakdown
  const oct20Breakdown = report.dailyBreakdown.find(d => d.date === '2026-10-20');
  assert.strictEqual(oct20Breakdown.issues[0], 'Relieved', 'Oct 20 punch must not extend employment');
  assert.strictEqual(oct20Breakdown.workingMinutes, 0, 'Post-relieved punch workingMinutes must be 0');

  console.log('✓ PASS: Attendance punches after relieving date do NOT extend employment or credit active salary.');
}

